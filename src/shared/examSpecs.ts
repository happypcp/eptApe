export function formatExamScore(examCode: string, rawScore: number | null | undefined): string {
  if (rawScore === null || rawScore === undefined || Number.isNaN(rawScore)) return '—';
  if (examCode === 'ielts_academic' || examCode === 'ielts_general') {
    const rounded = Math.round(rawScore * 2) / 2;
    return `Band ${rounded.toFixed(1)}`;
  }
  if (examCode === 'det') {
    const rounded = Math.max(10, Math.min(160, Math.round(rawScore / 5) * 5));
    return `${rounded} / 160`;
  }
  const rounded = Math.max(10, Math.min(90, Math.round(rawScore)));
  return `${rounded} / 90`;
}

export function scalePercentageToExamScore(examCode: string, pct: number): number {
  const clamped = Math.max(0, Math.min(1, pct));
  if (examCode === 'ielts_academic' || examCode === 'ielts_general') {
    const rawBand = 2.5 + clamped * 6.5;
    return Math.round(rawBand * 2) / 2;
  }
  if (examCode === 'det') {
    const rawDet = 30 + clamped * 130;
    return Math.round(rawDet / 5) * 5;
  }
  return Math.round(10 + clamped * 80);
}
